a = torch.randn(2048, 2048, dtype=torch.float32); b = torch.randn(2048, 2048, dtype=torch.float32)
c_cpu = a @ b; s_cpu = c_cpu.sum()
ag, bg = a.cuda(), b.cuda()
c_gpu = ag @ bg; s_gpu = c_gpu.sum(); torch.cuda.synchronize()
print("matmul device", c_gpu.device)
print("matmul max_abs_diff", (c_gpu.cpu() - c_cpu).abs().max().item())
