// Exploration 3: CSV/COPY details and recursive-pattern semantics needed by the arm.
const lbug = require('@ladybugdb/core');
const fs = require('fs');
const J = (r) => JSON.stringify(r, (k, v) => (typeof v === 'bigint' ? Number(v) : v));
const db = new lbug.Database(':memory:');
const c = new lbug.Connection(db);
const q = (x) => { try { const r = c.querySync(x); return (Array.isArray(r) ? r[r.length - 1] : r).getAllSync(); } catch (e) { return 'ERR ' + String(e.message || e).slice(0, 300); } };
const D = '/tmp/x3'; fs.mkdirSync(D, { recursive: true });
fs.writeFileSync(D + '/n.csv', 'id,sid,ls,text\n1,"a,b",,x y x\n2,b,3,"q ""z"""\n3,c,4,\n4,d,5,y\n');
fs.writeFileSync(D + '/e.csv', 'class,src,dst,weight,n_ev\nstructure,1,2,1,1\nmembership,2,3,0.5,2\nstructure,3,4,1,1\n');
console.log(q('CREATE NODE TABLE N(id INT64, sid STRING, ls INT64, text STRING, blk BOOLEAN, PRIMARY KEY(id))'));
console.log('copy n', J(q(`COPY N FROM (LOAD FROM '${D}/n.csv' (header=true, parallel=false) RETURN CAST(id AS INT64), sid, CAST(ls AS INT64), text, false)`)));
console.log(J(q('MATCH (n:N) RETURN n.*')));
console.log(q('CREATE REL TABLE F(FROM N TO N, w DOUBLE, n INT64)'));
console.log('copy rel where', J(q(`COPY F FROM (LOAD FROM '${D}/e.csv' (header=true) WHERE class = 'structure' RETURN CAST(src AS INT64), CAST(dst AS INT64), CAST(weight AS DOUBLE), CAST(n_ev AS INT64))`)));
console.log('copy rel append', J(q(`COPY F FROM (LOAD FROM '${D}/e.csv' (header=true) WHERE class = 'membership' RETURN CAST(dst AS INT64), CAST(src AS INT64), CAST(weight AS DOUBLE), CAST(n_ev AS INT64))`)));
console.log(J(q('MATCH (a:N)-[r:F]->(b:N) RETURN a.id, b.id, r.w, r.n')));
console.log('types', J(q("LOAD FROM '" + D + "/e.csv' (header=true) RETURN * LIMIT 1")));
console.log(J(c.querySync("LOAD FROM '" + D + "/e.csv' (header=true) RETURN * LIMIT 1").getColumnDataTypesSync()));
// recursive semantics: predicate on source / endpoint
q('MATCH (n:N {id: 1}) SET n.blk = true'); q('MATCH (n:N {id: 3}) SET n.blk = true');
console.log('pred src+end', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 1..5 (r, n | WHERE NOT n.blk)]->(v:N) RETURN v.id, length(p)')));
console.log('pred none', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 1..5]->(v:N) RETURN v.id, length(p)')));
console.log('zero lower', J(q('MATCH (s:N {id:1})-[p:F*0..2]->(v:N) RETURN v.id, length(p)')));
console.log('zero lower shortest', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 0..2]->(v:N) RETURN v.id, length(p)')));
console.log('segments', J(q('MATCH (s:N {id:1})-[p:F*0..1]->(x:N)-[p2:F*1..2]->(v:N) RETURN x.id, v.id, length(p)+length(p2)')));
console.log('depth 100', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 1..100]->(v:N) RETURN v.id, length(p)')));
console.log('depth 5000', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 1..5000]->(v:N) RETURN v.id, length(p)')));
console.log('max depth setting', J(q('CALL var_length_extend_max_depth=5000')));
console.log('depth 5000b', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 1..5000]->(v:N) RETURN v.id, length(p)')));
console.log('walk 5000', J(q('MATCH (s:N {id:1})-[p:F*1..5000]->(v:N) RETURN v.id, length(p)')));
console.log('int div', J(q('RETURN 7 / 2, 7 % 3, [10,20,30][1], list_extract([10,20,30], 2)')));
console.log('split', J(q("RETURN string_split('a b  c', ' '), size(string_split('', ' '))")));
console.log('unwind param', J(c.executeSync(c.prepareSync('UNWIND $F AS f MATCH (u:N {id: f[1]})-[r:F]->(v:N) RETURN f[2] AS h, u.id, v.id'), { F: [[1, 0], [2, 1]] }).getAllSync()));
console.log('rels props', J(q('MATCH (s:N {id:1})-[p:F* SHORTEST 1..3]->(v:N) RETURN v.id, properties(rels(p), "w"), properties(nodes(p), "id")')));
console.log('lbl', J(q('MATCH (a:N)-[r:F]->(b:N) RETURN label(r) LIMIT 1')));
console.log('threads', J(q("CALL threads=2")), J(q("CALL current_setting('threads') RETURN *")));
console.log('settings', J(q('CALL current_setting(\'var_length_extend_max_depth\') RETURN *')));
process.exit(0);
