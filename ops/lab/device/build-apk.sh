#!/usr/bin/env bash
# FixFlow device lab: build the LAB APK of the technician app (ship plan 7.5, phase L3a).
#
#   bash ops/lab/device/build-apk.sh [git-ref]      default ref: origin/main
#
# Checks <git-ref> out into a detached throwaway worktree under $LAB_OUT/src (never into an
# existing checkout's technician-app/), then runs L2's ops/lab/android-compile.sh on it with a
# hook (FF_ANDROID_HOOK) that, IN THE CONTAINER COPY ONLY:
#   - writes technician-app/.env with EXPO_PUBLIC_API_URL=http://10.0.2.2:<FF_LAB_PORT> (the
#     only API host a lab build may bake: plan 7.5) and an empty EXPO_PUBLIC_SENTRY_DSN;
#   - adds a config plugin that sets android:usesCleartextTraffic="true" (the lab backend is
#     plain HTTP; Android 9+ refuses cleartext by default in release builds);
#   - replaces google-services.json with a DUMMY Firebase project (push registration fails
#     instead of reaching the production Firebase project).
# L2's summary marks the run "MODIFIED" because of the hook: correct, this is a lab build, not
# a gate result. The APK is signed with the prebuild template's public debug key and is for
# the emulator only (app.sh install refuses a bundle that names any non-lab FixFlow host).
#
# A Gradle build takes TWO ff-slot slots: stop the emulator first (emu.sh stop), or the build
# waits. Cold ~25 min on this machine (L2's measurement), faster with the Gradle cache warm.
# Output: $LAB_OUT/apk/lab-COMPILE-ONLY-debugkey-<sha12>-p<port>.apk (L2's never-install marker kept:
# debug-signed, emulator only) and a .txt beside it with the build facts.
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$HERE/lib.sh"

REF="${1:-origin/main}"
REPO="$(git -C "$(winpath "$HERE")" rev-parse --show-toplevel)"
COMPILE="$REPO/ops/lab/android-compile.sh"
[ -f "$COMPILE" ] || die "L2's $COMPILE is not on this branch yet (merge claude/l2-android-compile-gate-3d0bf0)"

git -C "$REPO" fetch -q origin main 2> /dev/null || true
SHA="$(git -C "$REPO" rev-parse "$REF^{commit}")" || die "unknown ref $REF"
SRC="$LAB_OUT/src/app-${SHA:0:12}"
if [ ! -d "$SRC/technician-app" ]; then
  mkdir -p "$LAB_OUT/src"
  git -C "$REPO" -c core.longpaths=true worktree add --detach "$(winpath "$SRC")" "$SHA" > /dev/null ||
    die "cannot create the build worktree at $SRC"
fi
[ -d "$SRC/technician-app/android" ] && die "$SRC/technician-app/android exists: refusing (a native project must never be in a checkout)"

HOOK="$LAB_OUT/src/lab-hook-p$LAB_PORT.sh"
cat > "$HOOK" << EOF
#!/usr/bin/env bash
# Generated by ops/lab/device/build-apk.sh. Runs INSIDE the build container, in the copy
# (/work/technician-app), after npm ci and before expo prebuild. Never run on the host.
set -euo pipefail
[ "\$(pwd)" = /work/technician-app ] || { echo "hook must run in /work/technician-app" >&2; exit 2; }
printf 'EXPO_PUBLIC_API_URL=%s\nEXPO_PUBLIC_SENTRY_DSN=\n' "$LAB_API_URL" > .env
rm -f .env.local .env.production .env.production.local
# Firebase: a DUMMY project, never the production one. With the real google-services.json the
# lab emulator registered with the production Firebase project for push (L3a review, 2026-11-13);
# with this one that registration simply fails. Package name must match for the gradle plugin.
cat > google-services.json << 'GS'
{
  "project_info": { "project_number": "000000000000", "project_id": "fixflow-lab-dummy", "storage_bucket": "fixflow-lab-dummy.appspot.com" },
  "client": [
    {
      "client_info": { "mobilesdk_app_id": "1:000000000000:android:0000000000000000", "android_client_info": { "package_name": "com.fixflow.technician" } },
      "oauth_client": [],
      "api_key": [{ "current_key": "AIzaLabDummyKeyNotARealKey000000000000" }],
      "services": { "appinvite_service": { "other_platform_oauth_client": [] } }
    }
  ],
  "configuration_version": "1"
}
GS
mkdir -p plugins
cat > plugins/lab-cleartext.js << 'JS'
// FixFlow device lab only: allow plain-HTTP to the lab backend at 10.0.2.2.
const { withAndroidManifest } = require("expo/config-plugins");
module.exports = (config) =>
  withAndroidManifest(config, (c) => {
    c.modResults.manifest.application[0].\$["android:usesCleartextTraffic"] = "true";
    return c;
  });
JS
node -e '
  const fs = require("fs");
  const a = JSON.parse(fs.readFileSync("app.json", "utf8"));
  a.expo.plugins = (a.expo.plugins || []).concat(["./plugins/lab-cleartext.js"]);
  fs.writeFileSync("app.json", JSON.stringify(a, null, 2));
'
echo "lab hook: API base $LAB_API_URL written to .env; cleartext plugin added; dummy Firebase project (copy only)"
EOF

log "building the lab APK of ${SHA:0:12} ($REF) with API $LAB_API_URL; needs 2 slots"
FF_ANDROID_HOOK="$HOOK" FF_LAB_OUT="$LAB_ROOT" bash "$COMPILE" "$LAB_LANE" "$(winpath "$SRC")" release
rc=$?
OUTDIR="$(ls -dt "$LAB_OUT"/android-* 2> /dev/null | head -n1)"
[ "$rc" -eq 0 ] || die "android-compile.sh failed (rc=$rc); see $OUTDIR/summary.txt"
mkdir -p "$LAB_OUT/apk"
APK="$LAB_OUT/apk/lab-COMPILE-ONLY-debugkey-${SHA:0:12}-p$LAB_PORT.apk"
# L2 names its output COMPILE-ONLY-debugkey-*: debug-signed, for the emulator only (app.sh refuses
# anything that is not an emulator), never a phone or a store.
cp "$OUTDIR/COMPILE-ONLY-debugkey-release.apk" "$APK" || die "cannot copy the APK out of $OUTDIR"
{
  echo "ref: $REF"
  echo "commit: $SHA"
  echo "api_base: $LAB_API_URL"
  echo "build_dir: $OUTDIR"
  cat "$OUTDIR/summary.txt"
} > "${APK%.apk}.txt"
echo "lab APK: $APK"
