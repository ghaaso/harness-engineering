"""Register one Stage A evidence lane.

Reads A-research/<LANE>/claims.raw.json (researcher output), verdicts.json (verifier output) and,
when present, refutations.json (refuter votes from the full-rigour run) and lane.json (title, gaps).
Writes claims.json (claims with verification and status) and evidence.md (reader-facing note).

Status rules (lean mode, see WORKFLOW.md):
  unchecked  no verdict
  rejected   verdict not supported/partial, or two refuters refuted
  contested  critical claim with contrary evidence the verifier judged refuting, or one refuter refuted
  qualified  verdict partial (use corrected_statement)
  confirmed  verdict supported

Usage: python -B register_lane.py <root> <LANE>
"""
import json
import sys
from pathlib import Path

OK = ("supported", "partial")


def load(path, default):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def judge(c, v, votes):
    if not v:
        return "unchecked", "no verifier result"
    if v.get("verdict") not in OK:
        return "rejected", f"verdict {v.get('verdict')}"
    depth = ["source check"]
    if c.get("critical"):
        if votes is not None:
            refuted = sum(1 for x in votes if x.get("refuted"))
            depth.append(f"refuters reported {len(votes)} of 2, refuted {refuted}")
            if len(votes) >= 2 and refuted >= 2:
                return "rejected", "; ".join(depth)
            if refuted == 1:
                return "contested", "; ".join(depth)
        con = v.get("contrary") or {}
        if con:
            depth.append("contrary-evidence search" + (": refuting evidence found" if con.get("refutes") else ": nothing refuting"))
            if con.get("refutes"):
                return "contested", "; ".join(depth)
        elif votes is None:
            depth.append("no contrary-evidence search recorded")
    return ("qualified" if v.get("verdict") == "partial" else "confirmed"), "; ".join(depth)


def cell(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def src(c):
    out = []
    for s in c.get("sources") or []:
        bits = [s.get("title", "")]
        meta = ", ".join(x for x in (s.get("authors", ""), s.get("venue", ""), str(s.get("year", "") or "")) if x)
        if meta:
            bits.append(f"({meta})")
        bits.append(f"[{s.get('tier', '')}]")
        if s.get("url"):
            bits.append(s["url"])
        if s.get("locator"):
            bits.append(f"loc: {s['locator']}")
        out.append(" ".join(b for b in bits if b))
    return "; ".join(out)


def main(root, lane):
    d = Path(root) / "A-research" / lane
    raw = load(d / "claims.raw.json", None)
    if raw is None:
        sys.exit(f"{lane}: claims.raw.json missing")
    verdicts = {v["id"]: v for v in load(d / "verdicts.json", [])}
    refs = load(d / "refutations.json", None)
    meta = load(d / "lane.json", {})

    claims = []
    for c in raw:
        v = verdicts.get(c["id"])
        votes = refs.get(c["id"], []) if (refs is not None and c.get("critical")) else None
        status, depth = judge(c, v, votes)
        claims.append({**c, "verification": v, "refutations": votes or [], "status": status, "check_depth": depth})
    (d / "claims.json").write_text(json.dumps(claims, indent=2, ensure_ascii=False), encoding="utf-8")

    tally = {}
    for c in claims:
        tally[c["status"]] = tally.get(c["status"], 0) + 1

    def stmt(c):
        v = c.get("verification") or {}
        return (v.get("corrected_statement") or c["statement"]) if c["status"] == "qualified" else c["statement"]

    L = [f"# {lane}: {meta.get('title', '')}".rstrip(": "), ""]
    if meta.get("purpose"):
        L += [meta["purpose"], ""]
    L += [f"Status tally: {json.dumps(tally)}. Generated by `tools/register_lane.py` from claims.raw.json and verdicts.json; claims.json is the canonical record.", ""]
    L += ["Use rules: confirmed and qualified claims may be used (qualified only in the corrected wording); contested only with the caveat; rejected and unchecked never.", ""]
    usable = [c for c in claims if c["status"] in ("confirmed", "qualified")]
    L += ["## Confirmed and qualified", "", "| ID | Status | Statement | Label | Numbers | Source | Check |", "| --- | --- | --- | --- | --- | --- | --- |"]
    L += [f"| {c['id']}{' (critical)' if c.get('critical') else ''} | {c['status']} | {cell(stmt(c))} | {c.get('label', '')} | {cell(c.get('numbers', ''))} | {cell(src(c))} | {cell(c['check_depth'])} |" for c in usable]
    cont = [c for c in claims if c["status"] == "contested"]
    L += ["", "## Contested (use only with the caveat)", "", "| ID | Statement | Why contested |", "| --- | --- | --- |"]
    for c in cont:
        reasons = [x.get("reason", "") for x in c["refutations"] if x.get("refuted")]
        con = (c.get("verification") or {}).get("contrary") or {}
        if con.get("refutes"):
            reasons.append(con.get("reason", ""))
        L.append(f"| {c['id']} | {cell(c['statement'])} | {cell(' / '.join(r for r in reasons if r) or c['check_depth'])} |")
    fl = [c for c in claims if c.get("kind") in ("failure", "limit", "counter-evidence") and c["status"] not in ("rejected", "unchecked")]
    L += ["", "## Failures, limits and counter-evidence", ""]
    L += [f"- **{c['id']}** ({c['kind']}, {c['status']}): {stmt(c)}" for c in fl] or ["- none registered"]
    bad = [c for c in claims if c["status"] in ("rejected", "unchecked")]
    L += ["", "## Rejected and unchecked (never use)", "", "| ID | Status | Statement | Reason |", "| --- | --- | --- | --- |"]
    for c in bad:
        v = c.get("verification") or {}
        L.append(f"| {c['id']} | {c['status']} | {cell(c['statement'])} | {cell((v.get('verdict', '') + ': ' + v.get('note', '')) if v else c['check_depth'])} |")
    L += ["", "## Open gaps", ""]
    L += [f"- {g}" for g in meta.get("gaps", [])] or ["- none recorded"]
    (d / "evidence.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    back = json.loads((d / "claims.json").read_text(encoding="utf-8"))
    assert [c["id"] for c in back] == [c["id"] for c in raw], "id mismatch"
    print(json.dumps({"lane": lane, "claims": len(back), "tally": tally, "files": [str(d / "claims.json"), str(d / "evidence.md")]}))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
