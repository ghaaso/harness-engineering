"""Deterministic facts about the current context window, and the task-state blocks to restore.

The ledger is generated by code, not by the model: files changed (successful tool
results only), large reads, background results, failed tool calls and user prompts
since the last compaction.

Restorable state is DECLARED, not guessed: either blocks between
`<!-- ctx:restore -->` and `<!-- /ctx:restore -->`, or whole sections whose heading
is exactly one of the configured names (Next action, Decisions, ...). Headings are
parsed with code-fence awareness and a section always includes its subsections.
"""
from __future__ import annotations

import hashlib
import re
from collections import Counter, OrderedDict
from pathlib import Path
from typing import Any

from core import (CHARS_PER_TOKEN, SHELL_TOOLS, STATE_FILE_RE, WRITE_TOOLS, clean, inside, is_compact_boundary,
                  iter_lines, rel, usage_tokens)

NOTIFICATION_RE = re.compile(r"<task-notification>.*?</task-notification>", re.S)
TAG_RE = {tag: re.compile(rf"<{tag}>(.*?)</{tag}>", re.S)
          for tag in ("task-id", "output-file", "status", "summary")}
HEADING_RE = re.compile(r"^ {0,3}(#{1,6})[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$")
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
MARK_OPEN, MARK_CLOSE = "<!-- ctx:restore -->", "<!-- /ctx:restore -->"
STALE_HEADING_RE = re.compile(r"(?i)\b(superseded|historical|archived|obsolete|deprecated)\b")
NUMBERING_RE = re.compile(r"^\s*(\d+[.)]|[A-Za-z][.)])\s+")


def _text_of(content: Any) -> str:
    """Text of a message or tool result, with lone surrogates (a string cut mid-emoji) replaced."""
    if isinstance(content, str):
        return clean(content)
    parts = []
    for block in content or []:
        if isinstance(block, dict) and isinstance(block.get("text"), str):
            parts.append(block["text"])
    return clean("\n".join(parts))


def _clip(text: str, n: int) -> str:
    text = " ".join(clean(text).split())
    return text if len(text) <= n else text[: n - 1] + "…"


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


# --- window ledger -----------------------------------------------------------------------------

def read_window(transcript: str | Path) -> dict[str, Any]:
    """Records and raw lines after the last compaction boundary, plus boundary count."""
    records: list[tuple[int, dict[str, Any]]] = []
    raw: list[str] = []
    boundaries = 0
    for n, line, rec in iter_lines(transcript):
        if is_compact_boundary(rec):
            boundaries += 1
            records, raw = [], []
            continue
        records.append((n, rec))
        raw.append(line)
    return {"records": records, "raw": raw, "boundaries": boundaries}


def build_ledger(records: list[tuple[int, dict[str, Any]]], root: Path) -> dict[str, Any]:
    tool_uses: dict[str, tuple[str, dict[str, Any], int]] = {}
    changed: "OrderedDict[str, Counter]" = OrderedDict()
    change_turn: dict[str, int] = {}
    reads: "OrderedDict[str, dict[str, Any]]" = OrderedDict()
    failures: list[dict[str, Any]] = []
    results: list[dict[str, Any]] = []
    prompts: list[dict[str, Any]] = []
    peak, turns, seen_ids = 0, 0, set()
    first_ts = last_ts = ""

    for n, rec in records:
        ts = rec.get("timestamp") or ""
        if ts:
            first_ts = first_ts or ts
            last_ts = ts
        msg = rec.get("message") or {}
        if rec.get("type") == "assistant":
            ctx = usage_tokens(rec)
            mid = msg.get("id")
            if ctx and mid not in seen_ids:
                seen_ids.add(mid)
                turns += 1
                peak = max(peak, ctx)
            for block in msg.get("content") or []:
                if isinstance(block, dict) and block.get("type") == "tool_use":
                    tool_uses[block.get("id") or ""] = (block.get("name") or "", block.get("input") or {}, turns)
            continue
        if rec.get("type") != "user":
            continue
        content = msg.get("content")
        if isinstance(content, str) and "<task-notification>" in content:
            for note in NOTIFICATION_RE.findall(content):
                item = {k: (m.group(1).strip() if (m := rx.search(note)) else "") for k, rx in TAG_RE.items()}
                item["line"] = n
                results.append(item)
            continue
        has_tool_result = False
        if isinstance(content, list):
            for block in content:
                if not isinstance(block, dict) or block.get("type") != "tool_result":
                    continue
                has_tool_result = True
                name, inp, turn = tool_uses.get(block.get("tool_use_id") or "", ("", {}, turns))
                text = _text_of(block.get("content"))
                failed = bool(block.get("is_error"))
                if name in WRITE_TOOLS:
                    path = inp.get("file_path") or inp.get("notebook_path")
                    if path and not failed:
                        key = rel(path, root)
                        changed.setdefault(key, Counter())[name] += 1
                        changed.move_to_end(key)
                        change_turn[key] = turn
                    elif path:
                        failures.append({"line": n, "command": f"{name} {rel(path, root)}", "error": _clip(text, 220)})
                elif name == "Read" and inp.get("file_path") and not failed:
                    key = rel(inp["file_path"], root)
                    entry = reads.setdefault(key, {"count": 0, "chars": 0, "ranges": []})
                    entry["count"] += 1
                    entry["chars"] += len(text)
                    if inp.get("offset") or inp.get("limit"):
                        start = int(inp.get("offset") or 1)
                        entry["ranges"].append(f"{start}-{start + int(inp.get('limit') or 0) - 1}"
                                               if inp.get("limit") else f"{start}-")
                    else:
                        entry["ranges"].append("all")
                elif name in SHELL_TOOLS and failed:
                    failures.append({"line": n, "command": _clip(str(inp.get("command") or ""), 140),
                                     "error": _clip(text, 220)})
        origin = (rec.get("origin") or {}).get("kind")
        if (has_tool_result or rec.get("isMeta") or rec.get("isCompactSummary")
                or rec.get("isVisibleInTranscriptOnly") or (origin and origin != "human")):
            continue  # tool results, harness notes and the previous compaction's summary are not prompts
        text = _text_of(content) if isinstance(content, list) else (content or "")
        if text and not text.startswith("[Request interrupted"):
            prompts.append({"line": n, "ts": ts, "text": text})

    return {"peak": peak, "turns": turns, "first_ts": first_ts, "last_ts": last_ts,
            "changed": changed, "change_turn": change_turn, "reads": reads,
            "failures": failures, "results": results, "prompts": prompts}


def render_ledger(led: dict[str, Any], budget: int, header: bool = True) -> str:
    """Compact markdown, most decision-relevant parts first, cut at a line boundary within the budget."""
    parts: list[str] = []
    if header:
        parts.append(f"Window: {led['turns']} API calls, peak ~{led['peak'] // 1000}k tokens, "
                     f"{led['first_ts'][:16]} to {led['last_ts'][:16]} UTC.")
    if led["changed"]:
        items = [f"{p} ({', '.join(f'{k}x{v}' for k, v in c.items())})"
                 for p, c in reversed(list(led["changed"].items()))]
        parts.append("- Files created/changed successfully (latest first): " + "; ".join(items[:25])
                     + (f"; +{len(items) - 25} more" if len(items) > 25 else ""))
    big = sorted(led["reads"].items(), key=lambda kv: -kv[1]["chars"])
    big = [(p, e) for p, e in big if e["chars"] >= 6000][:12]
    if big:
        parts.append("- Large reads: " + "; ".join(
            f"{p} [{', '.join(e['ranges'][-3:])}] ~{int(e['chars'] / CHARS_PER_TOKEN / 1000)}k tok"
            for p, e in big))
    if led["results"]:
        parts.append("- Background results (full text on disk): " + "; ".join(
            f"{r.get('task-id') or '?'} {r.get('status') or ''} -> {r.get('output-file') or '?'}"
            for r in led["results"][-10:]))
    if led["failures"]:
        parts.append("- Failed tool calls: " + "; ".join(
            f"[{f['command']}] {f['error'][:120]}" for f in led["failures"][-6:]))
    if led["prompts"]:
        parts.append("- User prompts in this window (latest last; transcript line for exact recall): " + " | ".join(
            f"L{p['line']}: {_clip(p['text'], 220)}" for p in led["prompts"][-8:]))
    out: list[str] = []
    used = 0
    for part in parts:
        if used + len(part) + 1 > budget:
            room = budget - used - 30
            if room > 200:
                out.append(part[:room].rstrip() + " […cut]")
            break
        out.append(part)
        used += len(part) + 1
    return "\n".join(out)


# --- task state file ---------------------------------------------------------------------------

def find_state_file(transcript: str | Path, root: Path, focus: str | None = None,
                    previous: str | None = None) -> str | None:
    """Per-session focus, else the state-like file this session changed most in the current window.

    Only files inside the project root qualify. Archived copies are ignored. A
    docs/tasks/<id>/task.md beats other names; the previous cycle's choice is the
    fallback when the current window has not touched any state file yet.
    """
    focus = focus if isinstance(focus, str) and focus else None
    previous = previous if isinstance(previous, str) and previous else None
    if focus and inside(root / focus, root) and (root / focus).is_file():
        return focus
    pending: dict[str, str] = {}
    window: Counter = Counter()
    last_line: dict[str, int] = {}
    session: Counter = Counter()
    for n, _, rec in iter_lines(transcript, needles=['"tool_use"', '"tool_result"', '"compact_boundary"']):
        if is_compact_boundary(rec):
            window.clear()
            continue
        content = (rec.get("message") or {}).get("content")
        if not isinstance(content, list):
            continue
        for block in content:
            if not isinstance(block, dict):
                continue
            if block.get("type") == "tool_use" and block.get("name") in WRITE_TOOLS:
                path = (block.get("input") or {}).get("file_path") or ""
                if path and STATE_FILE_RE.match(Path(path).name):
                    pending[block.get("id") or ""] = path
            elif block.get("type") == "tool_result" and not block.get("is_error"):
                path = pending.pop(block.get("tool_use_id") or "", None)
                if not path or not inside(path, root):
                    continue
                key = rel(path, root)
                if any(part.lower() == "archive" for part in Path(key).parts):
                    continue
                window[key] += 1
                session[key] += 1
                last_line[key] = n

    def best(counter: Counter) -> str | None:
        live = [k for k in counter if (root / k).is_file()]
        if not live:
            return None
        return max(live, key=lambda k: (bool(re.match(r"(?i)docs/tasks/[^/]+/task\.md$", k)), counter[k],
                                        last_line.get(k, 0)))

    choice = best(window)
    if choice:
        return choice
    if previous and inside(root / previous, root) and (root / previous).is_file():
        return previous
    return best(session)


def read_state_text(path: Path) -> tuple[str | None, str]:
    """Decode strictly; a file that cannot be restored exactly is reported, never approximated."""
    try:
        data = path.read_bytes()
    except OSError as exc:
        return None, f"cannot be read ({exc.__class__.__name__})"
    encoding = "utf-8"
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    elif data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        encoding = "utf-16"
    try:
        text = data.decode(encoding)
    except UnicodeDecodeError:
        return None, "is not valid UTF-8/UTF-16 text"
    if "\x00" in text:
        return None, "contains NUL characters"
    return text.replace("\r\n", "\n").replace("\r", "\n"), ""


def parse_headings(lines: list[str]) -> list[dict[str, Any]]:
    """ATX headings outside code fences, each with its subtree end line and heading path."""
    heads: list[dict[str, Any]] = []
    fence: str | None = None
    for i, line in enumerate(lines):
        m = FENCE_RE.match(line)
        if m:
            marker = m.group(1)
            if fence is None:
                fence = marker
            elif marker[0] == fence[0] and len(marker) >= len(fence) and line.strip() == marker:
                fence = None
            continue
        if fence:
            continue
        h = HEADING_RE.match(line)
        if h and h.group(2).strip():
            heads.append({"level": len(h.group(1)), "title": h.group(2).strip(), "start": i})
    stack: list[dict[str, Any]] = []
    for idx, head in enumerate(heads):
        head["end"] = len(lines)
        for nxt in heads[idx + 1:]:
            if nxt["level"] <= head["level"]:
                head["end"] = nxt["start"]
                break
        while stack and stack[-1]["level"] >= head["level"]:
            stack.pop()
        head["path"] = [h["title"] for h in stack] + [head["title"]]
        stack.append(head)
    return heads


def normalize_title(title: str) -> str:
    title = NUMBERING_RE.sub("", title)
    return " ".join(title.strip().strip(":").lower().split())


def restore_candidates(text: str, names: list[str], whole_file_budget: int,
                       mode: str | None = None) -> list[dict[str, Any]]:
    """Declared restorable blocks of a state file, in priority order (lower `rank` first).

    1. "marked": blocks between markers, when any marker pair exists (nothing else is then eligible).
    2. "whole": the whole file when it fits the budget.
    3. "sections": whole sections (with subsections) whose normalized heading equals a configured
       name and whose heading path does not say it is superseded/historical.
    Each block records the mode that produced it. Passing `mode` re-parses a later version of
    the file the same way a snapshot was built ("whole" ignores the budget, "sections" skips it).
    """
    lines = text.split("\n")
    blocks: list[dict[str, Any]] = []

    def add(label: str, start: int, end: int, rank: int, kind: str) -> None:
        body = "\n".join(lines[start:end]).strip("\n")
        if body.strip():
            label = label if len(label) <= 90 else "…" + label[-89:]
            blocks.append({"label": f"{label} (L{start + 1}-L{end})", "start": start, "end": end,
                           "rank": rank, "text": body, "sha": sha(body), "mode": kind})

    opens = [i for i, ln in enumerate(lines) if ln.strip() == MARK_OPEN]
    if opens and mode in (None, "marked"):
        for n, start in enumerate(opens):
            end = next((j for j in range(start + 1, len(lines)) if lines[j].strip() == MARK_CLOSE), None)
            if end is not None:
                add(f"marked block {n + 1}", start + 1, end, n, "marked")
        if blocks:
            return blocks
    if mode == "marked":
        return blocks
    if text.strip() and (mode == "whole" or (mode is None and len(text.strip()) <= whole_file_budget)):
        add("whole file", 0, len(lines), 0, "whole")
        return blocks
    wanted = {normalize_title(n): i for i, n in enumerate(names)}
    taken_until = -1
    for head in parse_headings(lines):
        if head["start"] < taken_until:
            continue  # inside an already selected section
        rank = wanted.get(normalize_title(head["title"]))
        if rank is None or any(STALE_HEADING_RE.search(t) for t in head["path"]):
            continue
        add(" > ".join(head["path"]), head["start"], head["end"], rank, "sections")
        taken_until = head["end"]
    return sorted(blocks, key=lambda b: (b["rank"], b["start"]))
